import type {
  CodeFile,
  Exercise,
  IssueCategory,
  LearningLevel,
  MissionType,
  Track,
} from '../../domain/exercise/types'
import { createStarterExercise } from './createStarterExercise'

interface CompactExerciseSpec {
  id: string
  title: string
  track: Track
  secondaryTracks?: Track[]
  topics: string[]
  concepts: string[]
  level: LearningLevel
  difficulty: Exercise['difficulty']
  missionType: MissionType
  estimatedMinutes: number
  goal: string
  context: string
  path: string
  language: string
  source: string[]
  solution: string[]
  line: number | [number, number]
  category: IssueCategory
  acceptedCategories?: IssueCategory[]
  diagnosis: string
  reasoning: string
  fix: string
  severity: 'low' | 'medium' | 'high' | 'critical'
}

const code = (...lines: string[]) => lines.join('\n')

function compactExercise(spec: CompactExerciseSpec) {
  const fileId = spec.id + '-file'
  const locations = Array.isArray(spec.line)
    ? [{ startLine: spec.line[0], endLine: spec.line[1] }]
    : [{ startLine: spec.line }]

  return createStarterExercise({
    id: spec.id,
    title: spec.title,
    track: spec.track,
    secondaryTracks: spec.secondaryTracks,
    topics: spec.topics,
    concepts: spec.concepts,
    level: spec.level,
    difficulty: spec.difficulty,
    missionType: spec.missionType,
    estimatedMinutes: spec.estimatedMinutes,
    requirement: {
      summary: spec.goal,
      description: spec.context,
      acceptanceCriteria: [
        spec.fix.charAt(0).toUpperCase() + spec.fix.slice(1) + '.',
        'Preserve the intended successful behaviour.',
      ],
    },
    files: [
      {
        id: fileId,
        path: spec.path,
        language: spec.language,
        content: spec.source.join('\n'),
        changeType: 'modified',
      },
    ],
    findings: [
      {
        id: spec.id + '-finding',
        fileId,
        locations,
        category: spec.category,
        acceptedCategories: spec.acceptedCategories,
        concepts: spec.concepts,
        diagnosis: spec.diagnosis,
        reasoning: spec.reasoning,
        fix: spec.fix,
        severity: spec.severity,
        explanation:
          spec.diagnosis.charAt(0).toUpperCase() +
          spec.diagnosis.slice(1) +
          '. ' +
          spec.reasoning.charAt(0).toUpperCase() +
          spec.reasoning.slice(1) +
          '.',
        referenceComment:
          spec.diagnosis.charAt(0).toUpperCase() +
          spec.diagnosis.slice(1) +
          '; ' +
          spec.fix +
          '.',
      },
    ],
    referenceSolution: [
      {
        id: fileId,
        path: spec.path,
        language: spec.language,
        content: spec.solution.join('\n'),
        changeType: 'modified',
      },
    ],
    prerequisites: [],
  })
}

